from typing import Protocol

class Catalog(Protocol):
    def get(self, resource: str, identifier: str, lock: bool = False) -> dict | None: ...
    def list(self, resource: str, filters: dict | None = None) -> list[dict]: ...
    def save(self, resource: str, data: dict) -> dict: ...
    def delete(self, resource: str, identifier: str) -> None: ...
